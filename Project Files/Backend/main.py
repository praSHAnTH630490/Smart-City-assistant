
import os
import json

from dotenv import load_dotenv

from fastapi import FastAPI, HTTPException, Depends
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel

from sqlalchemy import create_engine, Column, Integer, String
from sqlalchemy.orm import sessionmaker, declarative_base

from ibm_watsonx_ai.foundation_models import ModelInference
from ibm_watsonx_ai.foundation_models.utils.enums import DecodingMethods
from ibm_watsonx_ai import Credentials


# ============================================================
# LOAD ENVIRONMENT VARIABLES
# ============================================================

load_dotenv()

WATSONX_API_KEY = os.getenv("WATSONX_API_KEY")
WATSONX_PROJECT_ID = os.getenv("WATSONX_PROJECT_ID")
WATSONX_URL = os.getenv("WATSONX_URL")


# ============================================================
# CHECK WATSONX CONFIGURATION
# ============================================================

if not WATSONX_API_KEY:
    raise RuntimeError(
        "WATSONX_API_KEY is missing from the .env file."
    )

if not WATSONX_PROJECT_ID:
    raise RuntimeError(
        "WATSONX_PROJECT_ID is missing from the .env file."
    )

if not WATSONX_URL:
    raise RuntimeError(
        "WATSONX_URL is missing from the .env file."
    )


# ============================================================
# WATSONX CREDENTIALS
# ============================================================

credentials = Credentials(
    api_key=WATSONX_API_KEY,
    url=WATSONX_URL
)


# ============================================================
# WATSONX MODEL
# ============================================================

model = ModelInference(
     model_id="ibm/granite-4-h-small",
    credentials=credentials,
    params={
        "decoding_method": DecodingMethods.GREEDY,
        "max_new_tokens": 200
    },
    project_id=WATSONX_PROJECT_ID
)


# ============================================================
# AI MODEL FUNCTION
# ============================================================

def call_model(prompt: str):

    try:

        response = model.generate_text(
            prompt=prompt
        )

        if isinstance(response, str):
            return response

        if isinstance(response, list):

            if len(response) > 0:
                return str(response[0])

        if isinstance(response, dict):

            if "generated_text" in response:
                return response["generated_text"]

            if "results" in response:

                results = response["results"]

                if results:

                    return results[0].get(
                        "generated_text",
                        "No response generated."
                    )

        return "No response generated by the AI model."

    except Exception as e:

        raise HTTPException(
            status_code=503,
            detail=f"AI model call failed: {str(e)}"
        )


