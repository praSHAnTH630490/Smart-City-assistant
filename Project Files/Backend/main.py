# ============================================================
# KPI FORECAST
# ============================================================

@app.post("/forecast-kpi")
def forecast_kpi(payload: AnomalyPayload):

    if not payload.data:

        raise HTTPException(
            status_code=400,
            detail="Historical data cannot be empty."
        )

    prompt = f"""
You are a data forecasting assistant.

Historical data:
{payload.data}

Forecast the next 3 values.

Return ONLY a JSON list.

Example:
[21, 24, 27]
"""

    raw_response = call_model(prompt)

    forecast = []

    try:

        cleaned = raw_response.strip()

        if cleaned.startswith("```"):

            cleaned = cleaned.replace(
                "```json",
                ""
            )

            cleaned = cleaned.replace(
                "```",
                ""
            )

            cleaned = cleaned.strip()

        forecast = json.loads(cleaned)

        if not isinstance(forecast, list):

            forecast = []

    except Exception:

        forecast = []

    return {
        "forecast_next_3_periods": forecast,
        "raw_response": raw_response
    }


# ============================================================
# SUBMIT FEEDBACK
# ============================================================

@app.post("/submit-feedback")
def submit_feedback(
    fb: FeedbackModel,
    db=Depends(get_db)
):

    user_id = fb.user_id.strip()
    message = fb.message.strip()

    if not user_id:

        raise HTTPException(
            status_code=400,
            detail="User name cannot be empty."
        )

    if not message:

        raise HTTPException(
            status_code=400,
            detail="Feedback cannot be empty."
        )

    entry = Feedback(
        user_id=user_id,
        message=message
    )

    db.add(entry)
    db.commit()
    db.refresh(entry)

    return {
        "message": "Feedback submitted successfully"
    }


