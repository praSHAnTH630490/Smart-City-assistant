@app.post("/chat")
def chat_endpoint(payload: Prompt):

    prompt = payload.prompt.strip()

    if not prompt:

        raise HTTPException(
            status_code=400,
            detail="Prompt cannot be empty."
        )

    return {
        "response": call_model(prompt)
    }


