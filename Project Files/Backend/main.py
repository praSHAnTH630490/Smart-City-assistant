@app.get("/updates")
def city_updates(city: str):

    city = city.strip()

    if not city:

        raise HTTPException(
            status_code=400,
            detail="City name cannot be empty."
        )

    prompt = f"""
Give the latest city-related updates about {city}.

Include:
- Local happenings
- IT industry news
- General city developments

Return JSON in this format:

{{
    "description": "City updates",
    "temp": 31
}}
"""

    try:

        raw_response = call_model(prompt)

        try:

            cleaned = raw_response.strip()

            if cleaned.startswith("```"):

                cleaned = cleaned.replace(
                    "```json",
                    ""
                )

                cleaned = cleaned.replace(
                    "```",
                    ""
                )

                cleaned = cleaned.strip()

            parsed = json.loads(cleaned)

        except json.JSONDecodeError:

            parsed = {
                "description": raw_response,
                "temp": None
            }

        return {
            "updates": parsed
        }

    except HTTPException:

        raise

    except Exception as e:

        raise HTTPException(
            status_code=500,
            detail=f"AI error: {str(e)}"
        )
